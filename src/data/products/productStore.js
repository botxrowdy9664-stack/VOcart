const productImageModules = import.meta.glob('../../assets/PRODUCT-IMAGES/*.{avif,jpg,jpeg,png,webp}', {
  eager: true,
  import: 'default',
});

const productImageExtensionPriority = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];

const normalizeProductImageName = (value) =>
  value
    .toLowerCase()
    .replace(/\.(avif|jpe?g|png|webp)$/iu, '')
    .replace(/-\(next\)$/iu, '')
    .replace(/["/]/gu, ' ')
    .replace(/[()]/gu, ' ')
    .replace(/[^a-z0-9]+/gu, ' ')
    .trim();

const isNextProductImage = (fileName) => /-\(next\)\.[^.]+$/iu.test(fileName);

const getProductImageExtensionRank = (fileName) => {
  const normalizedFileName = fileName.toLowerCase();
  const matchedIndex = productImageExtensionPriority.findIndex((extension) => normalizedFileName.endsWith(extension));
  return matchedIndex === -1 ? productImageExtensionPriority.length : matchedIndex;
};

const groupedProductImages = Object.entries(productImageModules).reduce((groups, [modulePath, source]) => {
  const fileName = modulePath.split('/').pop();
  const normalizedName = normalizeProductImageName(fileName);

  groups[normalizedName] ??= [];
  groups[normalizedName].push({ fileName, source });

  return groups;
}, {});

const productImageIndex = Object.fromEntries(
  Object.entries(groupedProductImages).map(([normalizedName, files]) => {
    const sortedFiles = [...files].sort((left, right) => {
      const nextWeight = Number(isNextProductImage(left.fileName)) - Number(isNextProductImage(right.fileName));

      if (nextWeight !== 0) {
        return nextWeight;
      }

      return getProductImageExtensionRank(left.fileName) - getProductImageExtensionRank(right.fileName);
    });

    const primaryImage = sortedFiles.find(({ fileName }) => !isNextProductImage(fileName)) ?? sortedFiles[0];
    const secondaryImage =
      sortedFiles.find(({ fileName }) => isNextProductImage(fileName)) ??
      sortedFiles.find(({ source }) => source !== primaryImage?.source) ??
      primaryImage;

    return [
      normalizedName,
      {
        primary: primaryImage?.source ?? '',
        secondary: secondaryImage?.source ?? primaryImage?.source ?? '',
      },
    ];
  }),
);

const getProductImage = (productName, occurrence = 1) => {
  const imageSet = productImageIndex[normalizeProductImageName(productName)];

  if (!imageSet) {
    return '';
  }

  return occurrence > 1 ? imageSet.secondary : imageSet.primary;
};
